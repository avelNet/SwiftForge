export function translator(language: InterfaceLanguage) {
  return (message: string, values: Record<string, string | number> = {}) => {
    const translated = language === "ru" ? russian[message] ?? message : message;
    return translated.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
  };
}

export type Translate = ReturnType<typeof translator>;
export const Locale = createContext<Translate>(translator("en"));
export const useLocale = () => useContext(Locale);
